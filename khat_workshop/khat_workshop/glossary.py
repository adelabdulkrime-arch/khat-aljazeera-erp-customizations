def entries():
    """كل المدخلات: (المصدر، العربية، السياق أو None)، بلا تكرار."""
    seen, out = set(), []
    for group in (DOCTYPES, REPORTS, WORKSPACES, CHROME, VALUES, MISC, FIELDS, HELP, MESSAGES, PASSWORD,
                  REPORT_LABELS, PRINT):
        for row in group:
            source, arabic = row[0], row[1]
            context = row[2] if len(row) > 2 else None
            key = (source, context)
            if key in seen:
                raise ValueError("glossary: مدخل مكرر %r (السياق %r)" % (source, context))
            seen.add(key)
            out.append((source, arabic, context))
    return out


def label(doctype):
    """الاسم العربي المفرد لمستند."""
    return dict(DOCTYPES).get(doctype, doctype)
